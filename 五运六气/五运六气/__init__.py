#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
五运六气 · 本地核心模块

心哥的纯本地五运六气推算引擎。既可独立 CLI 使用，
也可作为 Python 模块被小站（或任何外部系统）调用。

用法:
    from 五运六气 import 推算
    result = 推算("2026-07-26")
    print(result["岁运"]["描述"])

API 接口（dict 返回，便于 JSON 序列化）:
    - 推算(datestr)          → 完整结果
    - 年干支(year)           → (天干, 地支)
    - 岁运推算(year)         → dict
    - 六气推算(year)         → dict
    - 当前主客气(month, day) → dict
"""

from datetime import date
from typing import Union, Optional

# ============================================================
# 基础数据
# ============================================================

天干 = ["甲", "乙", "丙", "丁", "戊", "己", "庚", "辛", "壬", "癸"]
地支 = ["子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥"]

天干化运 = {
    "甲": "土", "乙": "金", "丙": "水", "丁": "木", "戊": "火",
    "己": "土", "庚": "金", "辛": "水", "壬": "木", "癸": "火",
}

阳干 = {"甲", "丙", "戊", "庚", "壬"}

地支化气 = {
    "子": "少阴君火", "丑": "太阴湿土", "寅": "少阳相火", "卯": "阳明燥金",
    "辰": "太阳寒水", "巳": "厥阴风木",
    "午": "少阴君火", "未": "太阴湿土", "申": "少阳相火", "酉": "阳明燥金",
    "戌": "太阳寒水", "亥": "厥阴风木",
}

客气顺序 = ["厥阴风木", "少阴君火", "太阴湿土", "少阳相火", "阳明燥金", "太阳寒水"]

司天在泉表 = {
    "少阴君火": "阳明燥金",
    "太阴湿土": "太阳寒水",
    "少阳相火": "厥阴风木",
    "阳明燥金": "少阴君火",
    "太阳寒水": "太阴湿土",
    "厥阴风木": "少阳相火",
}

主气顺序 = ["厥阴风木", "少阴君火", "少阳相火", "太阴湿土", "阳明燥金", "太阳寒水"]

# 节气划分（近似）
节气分段 = [
    ("初之气", (1, 20), (3, 20)),
    ("二之气", (3, 20), (5, 21)),
    ("三之气", (5, 21), (7, 22)),
    ("四之气", (7, 22), (9, 23)),
    ("五之气", (9, 23), (11, 22)),
    ("终之气", (11, 22), (1, 20)),
]

五行属性 = {
    "木": {"脏腑": ["肝", "胆"], "季节": "春", "气候": "风", "五味": "酸"},
    "火": {"脏腑": ["心", "小肠"], "季节": "夏", "气候": "暑", "五味": "苦"},
    "土": {"脏腑": ["脾", "胃"], "季节": "长夏", "气候": "湿", "五味": "甘"},
    "金": {"脏腑": ["肺", "大肠"], "季节": "秋", "气候": "燥", "五味": "辛"},
    "水": {"脏腑": ["肾", "膀胱"], "季节": "冬", "气候": "寒", "五味": "咸"},
}

# ============================================================
# 核心算法
# ============================================================

def 年干支(year: int) -> tuple:
    return (天干[(year - 4) % 10], 地支[(year - 4) % 12])


def 岁运推算(year: int) -> dict:
    tg, _ = 年干支(year)
    运 = 天干化运[tg]
    太过 = tg in 阳干
    label = "太过" if 太过 else "不及"
    五 = 五行属性[运]
    return {
        "年份": year,
        "天干": tg,
        "岁运": 运,
        "太过不及": label,
        "脏腑": 五["脏腑"],
        "季节": 五["季节"],
        "气候": 五["气候"],
        "五味": 五["五味"],
        "描述": f"{tg}年 → {运}运{label}",
    }


def 六气推算(year: int) -> dict:
    _, dz = 年干支(year)
    司天 = 地支化气[dz]
    在泉 = 司天在泉表[司天]
    司天_idx = 客气顺序.index(司天)

    步名 = ["初之气", "二之气", "三之气（司天）", "四之气", "五之气", "终之气（在泉）"]
    客气步 = {}
    for i, name in enumerate(步名):
        offset = (i - 2) % 6
        idx = (司天_idx + offset) % 6
        客气步[name] = 客气顺序[idx]

    return {
        "地支": dz,
        "司天": 司天,
        "在泉": 在泉,
        "客气六步": 客气步,
    }


def 当前主客气(month: int, day: int) -> dict:
    today = (month, day)

    def in_range(day, start, end):
        if start <= end:
            return start <= day < end
        else:
            return day >= start or day < end

    for idx, (step_name, start, end) in enumerate(节气分段):
        if in_range(today, start, end):
            return {
                "时段名称": step_name,
                "主气": 主气顺序[idx],
                "区间": f"{start[0]}月{start[1]}日 → {end[0]}月{end[1]}日",
            }

    return {"时段名称": "未知", "主气": "未知"}


def 客气六步分时(客气步表: dict) -> list:
    客气步简名 = {
        "初之气": 客气步表["初之气"],
        "二之气": 客气步表["二之气"],
        "三之气": 客气步表["三之气（司天）"],
        "四之气": 客气步表["四之气"],
        "五之气": 客气步表["五之气"],
        "终之气": 客气步表["终之气（在泉）"],
    }
    result = []
    for idx, (step_name, start, end) in enumerate(节气分段):
        客 = 客气步简名[step_name]
        marker = "👑司天" if step_name == "三之气" else ""
        marker = "⛲在泉" if step_name == "终之气" else marker
        result.append({
            "时段": step_name,
            "客气": 客,
            "主气": 主气顺序[idx],
            "日期": f"{start[0]}月{start[1]}日 → {end[0]}月{end[1]}日",
            "标记": marker,
        })
    return result


# ============================================================
# 统一推算接口（返回 dict）
# ============================================================

def 推算(d: Optional[Union[str, date]] = None) -> dict:
    """
    五运六气完整推算。

    参数:
        d: 日期。None=今天, "2026-07-26"字符串, 或 date 对象。
    返回:
        包含 岁运/六气/当前时位/六步详情 的字典。
    """
    if d is None:
        dt = date.today()
    elif isinstance(d, date):
        dt = d
    elif isinstance(d, str):
        dt = date.fromisoformat(d)
    else:
        raise TypeError(f"不支持的日期类型: {type(d)}")

    year, month, day = dt.year, dt.month, dt.day
    tg, dz = 年干支(year)
    运 = 岁运推算(year)
    气 = 六气推算(year)
    当前 = 当前主客气(month, day)
    客气分步 = 客气六步分时(气["客气六步"])
    五 = 五行属性[运["岁运"]]

    # 客气映射
    客气名映射 = {
        "初之气": "初之气", "二之气": "二之气",
        "三之气": "三之气（司天）",
        "四之气": "四之气", "五之气": "五之气",
        "终之气": "终之气（在泉）",
    }
    当前时段 = 当前["时段名称"]
    当前客气 = 气["客气六步"][客气名映射[当前时段]]

    return {
        "日期": dt.isoformat(),
        "干支": f"{tg}{dz}",
        "天干": tg,
        "地支": dz,
        "岁运": 运,
        "司天": 气["司天"],
        "在泉": 气["在泉"],
        "当前": {
            "时段": 当前时段,
            "主气": 当前["主气"],
            "客气": 当前客气,
            "区间": 当前["区间"],
        },
        "客气六步": 客气分步,
        "五行": 五,
        "描述": f"{dt.isoformat()} · {tg}{dz}年 · {运['岁运']}运{运['太过不及']} · "
                f"司天{气['司天']} 在泉{气['在泉']} · "
                f"当前{当前时段}(主气{当前['主气']} 客气{当前客气})",
    }
