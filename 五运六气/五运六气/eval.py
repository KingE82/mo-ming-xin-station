def 分析气候格局(五运六气结果: dict) -> dict:
    """
    从五运六气结果中提取当前的气候/体质特征。
    返回：主要矛盾、次要矛盾、宜忌方向。
    """
    岁运 = 五运六气结果["岁运"]
    当前 = 五运六气结果["当前"]
    司天 = 五运六气结果["司天"]
    在泉 = 五运六气结果["在泉"]

    年运 = 岁运["岁运"]
    年运气候 = 五行属性[年运]["气候"]
    年运脏腑 = 五行属性[年运]["脏腑"]
    年运太过 = 岁运["太过不及"]

    当前主气 = 当前["主气"]
    当前客气 = 当前["客气"]

    # 客气对应的气候
    客气气候 = {
        "厥阴风木": "风", "少阴君火": "暑",
        "太阴湿土": "湿", "少阳相火": "暑",
        "阳明燥金": "燥", "太阳寒水": "寒",
    }

    主气气候 = {
        "厥阴风木": "风", "少阴君火": "暑",
        "少阳相火": "暑", "太阴湿土": "湿",
        "阳明燥金": "燥", "太阳寒水": "寒",
    }

    客气候 = 客气气候.get(当前客气, "")
    主气候 = 主气气候.get(当前主气, "")
    气候标签 = []

    if 主气候 == 客气候 and 主气候:
        气候标签.append(f"双{客气候}（客主同气）")
    elif 主气候 and 客气候:
        气候标签.append(f"主{主气候}客{客气候}")

    # 年运加持
    年运标签 = f"年运{年运气候}{年运太过}"
    气候标签.append(年运标签)

    # 主要矛盾
    主要气候 = 客气候 or 主气候 or "平"
    次要维度 = []

    if "司天" in 当前.get("时段", ""):
        次要维度.append(f"司天{司天}")
    if "在泉" in 当前.get("时段", ""):
        次要维度.append(f"在泉{在泉}")

    return {
        "主要气候": 主要气候,
        "年运气候": 年运气候,
        "年运太过": 年运太过,
        "当前主气": 当前主气,
        "当前客气": 当前客气,
        "气候标签": "、".join(气候标签),
        "敏感脏腑": 年运脏腑,
        "年运方向": f"{年运气候}（{'太过/当令' if 年运太过 == '太过' else '不及/当令'})",
    }


def 评价食疗方案(五运六气结果: dict, 食疗方案: str) -> dict:
    """
    对给出的食疗方案做一致性评分。

    评分维度：
    1. 气候匹配度 — 方案是否针对当前气候做了调整
    2. 脏腑保护度 — 是否照顾到了敏感脏腑
    3. 宜忌符合度 — 是否避开了禁忌、采纳了有益的
    4. 五味平衡度 — 五味是否协调
    5. 整体合理性 — 综合评分
    """
    格局 = 分析气候格局(五运六气结果)
    方案文本 = 食疗方案.lower()

    主要气候 = 格局["主要气候"]
    敏感脏腑 = 格局["敏感脏腑"]
    气候标签 = 格局["气候标签"]

    # 寻找宜忌的匹配/冲突
    宜忌 = 气候宜忌.get(主要气候, {"宜": [], "忌": [], "宜食材举例": [], "忌食材举例": []})

    宜命中 = 0
    忌冲突 = 0
    for 宜 in 宜忌["宜食材举例"]:
        if 宜.lower() in 方案文本:
            宜命中 += 1
    for 忌 in 宜忌["忌食材举例"]:
        if 忌.lower() in 方案文本:
            忌冲突 += 1

    气候分 = 10
    if 宜命中 >= 2:
        气候分 = 10
    elif 宜命中 == 1:
        气候分 = 7
    else:
        气候分 = 5
    if 忌冲突 >= 1:
        气候分 = max(1, 气候分 - 3 * 忌冲突)

    # 脏腑保护度
    脏腑分 = 10
    for 脏 in 敏感脏腑:
        for 补 in 脏腑宜忌.get(脏, {}).get("补", []):
            if 补.lower() in 方案文本:
                脏腑分 = min(10, 脏腑分 + 2)
        for 泻 in 脏腑宜忌.get(脏, {}).get("泻", []):
            if 泻.lower() in 方案文本:
                脏腑分 = max(1, 脏腑分 - 2)

    # 五味均衡度（粗略判断）
    五味集 = {"酸": 0, "甘": 0, "辛": 0, "苦": 0, "咸": 0}
    for 味 in 五味集:
        if 味 in 方案文本:
            五味集[味] += 1
    有五味 = sum(1 for v in 五味集.values() if v > 0)
    五味分 = min(10, 有五味 * 2 + 2)

    # 整体
    综合分 = round((气候分 * 0.4 + 脏腑分 * 0.3 + 五味分 * 0.3), 1)

    # 建议
    建议列表 = []
    if 气候分 < 6:
        宜文 = "、".join(宜忌["宜"])
        忌文 = "、".join(宜忌["忌"])
        建议列表.append(f"当前气候以「{主要气候}」为主，方案宜{宜文}，忌{忌文}")
    if 脏腑分 < 6:
        脏名 = "、".join(敏感脏腑)
        建议列表.append(f"年运敏感脏腑为{脏名}，可增加针对性食材")
    if 五味分 < 6:
        建议列表.append("五味略显单一，建议适当增加不同性味的食材搭配")
    if 综合分 >= 8:
        建议列表.append("整体方案与当前气候格局较为协调")

    return {
        "五运六气格局": 气候标签,
        "主要气候": 主要气候,
        "敏感脏腑": "、".join(敏感脏腑),
        "评分": {
            "气候匹配度": 气候分,
            "脏腑保护度": 脏腑分,
            "五味均衡度": 五味分,
            "综合评分": 综合分,
        },
        "宜忌匹配": {
            "推荐食材命中": 宜命中,
            "禁忌食材冲突": 忌冲突,
        },
        "建议": 建议列表 if 建议列表 else ["方案基本合理，无需大调"],
    }


