    r = 推算(日期str)
    print("=" * 52)
    print(f"  食疗评价 · {r['描述']}")
    print("=" * 52)
    print(f"\n  方案：{食疗方案[:80]}{'…' if len(食疗方案) > 80 else ''}")
    print()

    ev = 评价食疗方案(r, 食疗方案)
    print(f"  ── 气候格局 ──")
    print(f"  主要气候：{ev['主要气候']}")
    print(f"  敏感脏腑：{ev['敏感脏腑']}")
    print()
    print(f"  ── 评分 ──")
    for k, v in ev["评分"].items():
        bar = "█" * max(0, min(10, int(v))) + "░" * max(0, 10 - int(v))
        print(f"  {k}：{v:.1f}  {bar}")
    print()
    print(f"  ── 宜忌匹配 ──")
    print(f"  推荐食材命中：{ev['宜忌匹配']['推荐食材命中']}")
    print(f"  禁忌食材冲突：{ev['宜忌匹配']['禁忌食材冲突']}")
    print()
    print(f"  ── 建议 ──")
    for 建议 in ev["建议"]:
        print(f"  · {建议}")
    print("=" * 52)


